def generate_static_obstacles(count, map_size, start_pos, goal_pos):
    obstacles = []
    min_dist = 4.0 # Minimum distance from start/goal
    
    for _ in range(count):
        valid = False
        while not valid:
            x = np.random.uniform(2.0, map_size - 2.0)
            y = np.random.uniform(2.0, map_size - 2.0)
            
            # Check distance from start
            d_start = np.hypot(x - start_pos[0], y - start_pos[1])
            # Check distance from goal
            d_goal = np.hypot(x - goal_pos[0], y - goal_pos[1])
            
            if d_start > min_dist and d_goal > min_dist:
                valid = True
                # Randomize radius
                r = np.random.uniform(0.8, 1.5)
                obstacles.append({'position': [float(x), float(y)], 'radius': float(r)})
    return obstacles

