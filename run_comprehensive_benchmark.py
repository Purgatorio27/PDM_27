        if os.path.exists(BACKUP_CONFIG_PATH):
            shutil.copy(BACKUP_CONFIG_PATH, SHARED_CONFIG_PATH)
            os.remove(BACKUP_CONFIG_PATH)
            print(f"\nRestored original {SHARED_CONFIG_PATH}")

